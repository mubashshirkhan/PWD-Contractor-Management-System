-- PostgreSQL schema design for the two existing SQLite datasets.
-- This file is design-only. It has not been executed against Neon or SQLite.
--
-- The main and location_ui schemas intentionally have independent identity
-- sequences. A tender_id appearing in both schemas is therefore preserved as
-- two records, not merged.

CREATE SCHEMA IF NOT EXISTS main;
CREATE SCHEMA IF NOT EXISTS location_ui;

-- Base schema is retained in both datasets, including the currently empty
-- organisations and run_organisations tables in location_ui.

CREATE TABLE main.organisations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    tender_count INTEGER NOT NULL,
    source_url TEXT NOT NULL,
    count_url TEXT NOT NULL,
    observed_at TEXT NOT NULL
);

CREATE TABLE main.tenders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tender_id TEXT NOT NULL UNIQUE,
    reference_number TEXT,
    title TEXT,
    organisation_chain TEXT NOT NULL,
    published_at TEXT,
    closing_at TEXT,
    opening_at TEXT,
    estimated_value TEXT,
    product_category TEXT,
    location_raw TEXT,
    location_city_village TEXT,
    location_taluka TEXT,
    location_district TEXT,
    location_state TEXT,
    location_provenance TEXT NOT NULL,
    location_confidence DOUBLE PRECISION NOT NULL,
    scope_status TEXT NOT NULL DEFAULT 'UNKNOWN',
    scope_district TEXT,
    scope_taluka TEXT,
    scope_provenance TEXT NOT NULL DEFAULT 'scope.unclassified',
    source_listing_url TEXT NOT NULL,
    source_detail_url TEXT NOT NULL,
    observed_at TEXT NOT NULL
);

CREATE TABLE main.source_evidence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tender_id TEXT NOT NULL REFERENCES main.tenders(tender_id),
    field_name TEXT NOT NULL,
    raw_value TEXT,
    source_page TEXT NOT NULL,
    extraction_method TEXT NOT NULL,
    observed_at TEXT NOT NULL
);

CREATE TABLE main.extraction_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TEXT NOT NULL,
    finished_at TEXT,
    max_organisations INTEGER NOT NULL,
    max_pages_per_organisation INTEGER NOT NULL,
    max_details_per_organisation INTEGER NOT NULL,
    status TEXT NOT NULL,
    summary_json TEXT
);

CREATE TABLE main.run_organisations (
    run_id BIGINT NOT NULL REFERENCES main.extraction_runs(id),
    organisation_name TEXT NOT NULL,
    status TEXT NOT NULL,
    PRIMARY KEY (run_id, organisation_name)
);

CREATE TABLE main.listing_pages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES main.extraction_runs(id),
    organisation_name TEXT NOT NULL,
    page_number INTEGER NOT NULL,
    source_url TEXT NOT NULL,
    tender_count INTEGER NOT NULL,
    page_fingerprint TEXT NOT NULL,
    next_url TEXT,
    observed_at TEXT NOT NULL,
    UNIQUE (run_id, organisation_name, page_number)
);

CREATE TABLE main.extraction_errors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES main.extraction_runs(id),
    organisation_name TEXT,
    stage TEXT NOT NULL,
    message TEXT NOT NULL,
    started_at TEXT NOT NULL,
    finished_at TEXT NOT NULL
);

CREATE TABLE main.tender_occurrences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tender_id TEXT NOT NULL,
    search_taluka TEXT NOT NULL,
    source_listing_url TEXT NOT NULL,
    page_number INTEGER NOT NULL,
    observed_at TEXT NOT NULL,
    UNIQUE (tender_id, search_taluka, source_listing_url)
);

-- The main SQLite source declares the source_evidence foreign key and it is
-- therefore retained above. The location source does not declare it and its
-- table below intentionally remains without that constraint.
--
-- The main tender_occurrences foreign key is deliberately not created here.
-- The source SQLite data contains seven orphan rows. Add the constraint only
-- after all main records have been imported:
--
-- ALTER TABLE main.tender_occurrences
--     ADD CONSTRAINT tender_occurrences_tender_fk
--     FOREIGN KEY (tender_id) REFERENCES main.tenders(tender_id)
--     NOT VALID;

CREATE TABLE main.coverage_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at TEXT NOT NULL,
    finished_at TEXT,
    status TEXT NOT NULL,
    worker_version TEXT NOT NULL,
    request_delay_seconds DOUBLE PRECISION NOT NULL,
    error TEXT
);

CREATE TABLE main.coverage_partitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district TEXT NOT NULL,
    taluka TEXT NOT NULL,
    year INTEGER,
    month INTEGER,
    status_filter TEXT NOT NULL,
    search_mode TEXT NOT NULL,
    date_from TEXT,
    date_to TEXT,
    portal_query_signature TEXT NOT NULL,
    state TEXT NOT NULL,
    started_at TEXT,
    finished_at TEXT,
    last_success_at TEXT,
    next_url TEXT,
    pages_discovered INTEGER NOT NULL DEFAULT 0,
    pages_processed INTEGER NOT NULL DEFAULT 0,
    tender_ids_discovered INTEGER NOT NULL DEFAULT 0,
    details_retrieved INTEGER NOT NULL DEFAULT 0,
    details_failed INTEGER NOT NULL DEFAULT 0,
    details_skipped INTEGER NOT NULL DEFAULT 0,
    last_error TEXT
);

CREATE TABLE main.coverage_pages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partition_id BIGINT NOT NULL REFERENCES main.coverage_partitions(id),
    page_number INTEGER NOT NULL,
    source_url TEXT NOT NULL,
    page_fingerprint TEXT NOT NULL,
    next_url TEXT,
    status TEXT NOT NULL,
    tender_count INTEGER NOT NULL DEFAULT 0,
    processed_at TEXT,
    error TEXT,
    UNIQUE (partition_id, page_number, page_fingerprint)
);

CREATE TABLE main.coverage_tender_work (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partition_id BIGINT NOT NULL REFERENCES main.coverage_partitions(id),
    tender_id TEXT NOT NULL,
    source_listing_url TEXT NOT NULL,
    detail_status TEXT NOT NULL,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    first_discovered_at TEXT NOT NULL,
    last_attempt_at TEXT,
    retrieved_at TEXT,
    failure_reason TEXT,
    skip_reason TEXT,
    UNIQUE (partition_id, tender_id)
);

CREATE TABLE main.tender_observations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tender_id TEXT NOT NULL REFERENCES main.tenders(tender_id),
    partition_id BIGINT NOT NULL REFERENCES main.coverage_partitions(id),
    retrieved_at TEXT NOT NULL,
    source_listing_url TEXT NOT NULL,
    source_detail_url TEXT NOT NULL,
    detail_content_hash TEXT NOT NULL,
    parsed_fields_json TEXT,
    sanitized_html TEXT,
    classification_status TEXT NOT NULL,
    classification_provenance TEXT NOT NULL,
    UNIQUE (tender_id, partition_id, detail_content_hash)
);

CREATE TABLE main.schema_migrations (
    version TEXT PRIMARY KEY,
    checksum TEXT NOT NULL,
    applied_at TEXT NOT NULL
);

CREATE TABLE location_ui.schema_migrations (
    version TEXT PRIMARY KEY,
    checksum TEXT NOT NULL,
    applied_at TEXT NOT NULL
);

CREATE INDEX idx_main_coverage_partitions_state
    ON main.coverage_partitions(state);
CREATE INDEX idx_main_coverage_pages_partition_status
    ON main.coverage_pages(partition_id, status);
CREATE INDEX idx_main_coverage_tender_work_status
    ON main.coverage_tender_work(partition_id, detail_status);
CREATE INDEX idx_main_tender_observations_tender
    ON main.tender_observations(tender_id, retrieved_at);

CREATE UNIQUE INDEX uq_main_coverage_partitions_logical
    ON main.coverage_partitions (
        district,
        taluka,
        CASE WHEN year IS NULL THEN 0 ELSE 1 END,
        COALESCE(year, 0),
        CASE WHEN month IS NULL THEN 0 ELSE 1 END,
        COALESCE(month, 0),
        CASE WHEN status_filter IS NULL THEN 0 ELSE 1 END,
        COALESCE(status_filter, ''),
        search_mode,
        CASE WHEN date_from IS NULL THEN 0 ELSE 1 END,
        COALESCE(date_from, ''),
        CASE WHEN date_to IS NULL THEN 0 ELSE 1 END,
        COALESCE(date_to, ''),
        portal_query_signature
    );

